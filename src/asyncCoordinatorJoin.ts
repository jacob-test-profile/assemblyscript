/** JS source of the join engine (joinPromises + createJoinRegistry). */
export const ASYNC_COORDINATOR_JOIN_SOURCE = `// Generated by asc: CPS async coordinator. Do not edit by hand.
// Drives the state machines produced by the CPS transform: each exported
// async function becomes a Promise-returning method on the api object.
// A suspending import is a user binding returning a Promise; the wrapper
// records that promise on the active task and returns 0, and the driver
// delivers its settlement through the matching resume/reject export.

// Joins already-issued member promises under one completion policy.
// Members settle in argument order for "all"/"allSettled"; late
// settlements after the join settles are dropped, never crash.
export function joinPromises(policy, members) {
  const list = members.map(function (m) { return Promise.resolve(m); });
  if (policy === 'all') {
    return new Promise(function (resolve, reject) {
      let settled = false;
      let remaining = list.length;
      const results = new Array(list.length);
      if (remaining === 0) { resolve(results); return; }
      list.forEach(function (p, i) {
        p.then(function (v) {
          if (settled) return;
          results[i] = v;
          if (--remaining === 0) { settled = true; resolve(results); }
        }, function (e) {
          if (settled) return;
          settled = true; reject(e);
        });
      });
    });
  }
  if (policy === 'race') {
    return new Promise(function (resolve, reject) {
      let settled = false;
      list.forEach(function (p) {
        p.then(function (v) {
          if (settled) return;
          settled = true; resolve(v);
        }, function (e) {
          if (settled) return;
          settled = true; reject(e);
        });
      });
    });
  }
  if (policy === 'allSettled') {
    return new Promise(function (resolve) {
      let remaining = list.length;
      const results = new Array(list.length);
      if (remaining === 0) { resolve(results); return; }
      list.forEach(function (p, i) {
        p.then(function (v) {
          results[i] = { status: 'fulfilled', value: v };
          if (--remaining === 0) resolve(results);
        }, function (e) {
          results[i] = { status: 'rejected', reason: e };
          if (--remaining === 0) resolve(results);
        });
      });
    });
  }
  if (policy === 'any') {
    return new Promise(function (resolve, reject) {
      let settled = false;
      let remaining = list.length;
      const errors = new Array(list.length);
      if (remaining === 0) {
        reject(asyncAggregateError(errors));
        return;
      }
      list.forEach(function (p, i) {
        p.then(function (v) {
          if (settled) return;
          settled = true; resolve(v);
        }, function (e) {
          if (settled) return;
          errors[i] = e;
          if (--remaining === 0) {
            settled = true;
            reject(asyncAggregateError(errors));
          }
        });
      });
    });
  }
  throw new Error('async coordinator: unknown join policy ' + policy);
}

function asyncAggregateError(errors) {
  if (typeof AggregateError !== 'undefined') {
    return new AggregateError(errors, 'All promises were rejected');
  }
  const error = new Error('All promises were rejected');
  error.errors = errors;
  return error;
}

// Registry for the issue/join shape: members are issued (non-suspending)
// and collected, then one suspending join settles them under a policy.
// join() consumes the members it joins; a member is consumed once.
export function createJoinRegistry() {
  let nextId = 1;
  const members = new Map();
  return {
    issue: function (promise) {
      const id = nextId++;
      members.set(id, Promise.resolve(promise));
      return id;
    },
    join: function (policy, ids) {
      let list;
      if (ids) {
        list = ids.map(function (id) {
          const p = members.get(id);
          if (!p) throw new Error('async coordinator: unknown join member ' + id);
          return p;
        });
        ids.forEach(function (id) { members.delete(id); });
      } else {
        list = Array.from(members.values());
        members.clear();
      }
      return joinPromises(policy, list);
    },
    pendingCount: function () { return members.size; }
  };
}

`;
